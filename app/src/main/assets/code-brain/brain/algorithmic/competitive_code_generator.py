    def _t_dual_collection_max(self, ins: list, result: str, details: dict) -> list[str]:
        """Dual-collection selection with a count constraint: #{X} >= #{Y}
        chosen, the maximum sum.  Both sorted descending; for each {Y}
        count k the {X} side contributes its best sum with at least k
        taken — the suffix maximum of the prefix sums over the VALID
        counts only (the tail is -inf: no phantom "zero extra" entry),
        and k never exceeds the {X} count (the constraint is then
        unsatisfiable).  The two collections are read as
        "N then N values / M then M values"."""
        return [
            "from itertools import accumulate",
            "",
            "N, M = map(int, input().split())",
            "B = sorted(map(int, input().split()), reverse=True)",
            "W = sorted(map(int, input().split()), reverse=True)",
            "bp = [0] + list(accumulate(B))",
            "wp = [0] + list(accumulate(W))",
            "sm = [float('-inf')] * (N + 2)",
            "for j in range(N, -1, -1):",
            "    sm[j] = max(bp[j], sm[j + 1])",
            result + " = max(wp[k] + sm[k] for k in range(0, min(M, N) + 1))",
            "print(" + result + ")",
        ]

