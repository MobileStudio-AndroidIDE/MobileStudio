    def _gen_output_step(self, out_step, plan, structured_problem) -> list[str]:
        details = out_step.details or {}
        # The plan's "skip" flag was designed for generators whose templates
        # print internally; this generator centralizes printing in the output
        # step, so the final result is always printed here.
        expr = out_step.input_vars[0] if out_step.input_vars else \
            (details.get("name") or "result")
        # Resolve a generic "result" reference to the last computed variable.
        if expr == "result" and plan.algorithm_steps \
                and plan.algorithm_steps[-1].output_vars:
            expr = plan.algorithm_steps[-1].output_vars[0]
        var_type = details.get("type", "default")

        semantic_type = ""
        out_vars = getattr(structured_problem, "output_variables", [])
        if out_vars:
            semantic_type = out_vars[0].semantic_type or ""
            if var_type in ("default", "unknown", ""):
                var_type = out_vars[0].var_type
        # When the output type is still unknown, use the algorithm step's
        # declared output type (the computation knows what it produces).
        if var_type in ("default", "unknown", "", "Any"):
            if plan.algorithm_steps and plan.algorithm_steps[-1].output_types:
                declared = plan.algorithm_steps[-1].output_types[-1] or ""
                if "List" in declared or "[]" in declared:
                    var_type = "int[]"

        # The VALUE's type decides the print form: a scalar value (the
        # computation's declared output) never goes through join/map —
        # the join form requires a collection.  The computation's
        # declared output type wins over the output format's
        # collection-ness when they conflict.
        if var_type in ("int[]_lines", "int[]", "array", "list[int]",
                        "collection") and plan.algorithm_steps \
                and plan.algorithm_steps[-1].output_types:
            declared = plan.algorithm_steps[-1].output_types[-1] or ""
            if declared and "List" not in declared and "[]" not in declared \
                    and declared not in ("int[]_lines",):
                return [f"print({expr})"]

        if semantic_type == "boolean":
            return [f'print("Yes" if {expr} else "No")']
        # Guarded join: when the runtime value turns out to be a scalar
        # or string (hypothesis produced a scalar where the declared
        # type says collection), a bare join would explode it into
        # characters ("No" -> "N o").  A list/tuple joins as declared;
        # anything else prints as-is.
        def _join_print(sep: str) -> str:
            return (f"print({sep!r}.join(map(str, {expr})) "
                    f"if isinstance({expr}, (list, tuple)) else {expr})")

        # Multiple output variables: a leading scalar count followed by a
        # collection ("C\nX_1 X_2 ...") → the count is len(collection).
        if len(out_vars) >= 2 and out_vars[0].var_type in ("int",) \
                and out_vars[1].var_type in ("int[]", "array", "collection"):
            return [f"print(len({expr}))", _join_print(" ")]
        if var_type == "int[]_lines" or semantic_type == "int[]_lines":
            return [_join_print("\n")]
        if var_type in ("int[]", "array", "list[int]", "collection"):
            return [_join_print(" ")]
        if var_type == "string[]":
            return [_join_print(" ")]
        # Layout from the problem's own samples: a per-element fit makes
        # the value a list — join one value per line when the sample
        # output is multi-line, per token when it is a single line of
        # several values.  Scalars and strings print as-is (the
        # isinstance guard), so this is safe for every other shape too.
        _samples = getattr(structured_problem, "sample_cases", None) or []
        if _samples:
            _first = (_samples[0].output_text or "").strip()
            if "\n" in _first:
                return [_join_print("\n")]
            if len(_first.split()) > 1:
                return [_join_print(" ")]
        return [f"print({expr})"]


