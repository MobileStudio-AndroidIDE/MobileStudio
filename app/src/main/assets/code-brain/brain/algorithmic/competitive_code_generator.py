    def _t_index_chain(self, ins: list, result: str, details: dict, sp) -> list[str]:
        """Chained references through collections, for each index.

        General indirect-reference dataflow (no dedicated operation):
            for each i in indices(V0):        (or values 1..N for inverse)
                v0 = V0[i]                    (or V0.index(i))
                v1 = V1[v0]
                ...
            result[i] = vk

        Index adjustment: an inverse lookup yields a position (used as-is);
        a direct lookup yields a value, which needs the 1->0 index
        adjustment for stdio problems (AtCoder-style 1-indexed values) and
        none for call-based problems.
        """
        chain_steps = details.get("steps") or []
        if not chain_steps:
            raise ValueError("index_chain requires chain steps")
        # Value index adjustment: 1-indexed values for stdio problems
        value_adjust = " - 1" if bool(getattr(sp, "uses_stdio", True)) else ""
        first_kind, first_col = chain_steps[0]

        lines = [f"{result} = []"]
        # Performance: a repeated .index() inside the loop is O(N) per
        # iteration (O(N^2) total) — the reverse position map, built once
        # before the loop, makes each lookup O(1).  Same semantics: the
        # position of the value in the collection.
        inv_cols = []
        seen_inv = set()
        for kind, col in chain_steps:
            if kind == "inverse" and col not in seen_inv:
                seen_inv.add(col)
                inv_cols.append(col)
        for col in inv_cols:
            lines.append(f"_pos_{col} = {{v: k for k, v in enumerate({col})}}")
        if first_kind == "inverse":
            lines.append(f"for i in range(1, len({first_col}) + 1):")
            # An inverse lookup yields a position — used as-is downstream
            bound = f"_pos_{first_col}[i]"
            bound_is_position = True
        else:
            lines.append(f"for i in range(len({first_col})):")
            # A direct access with the loop position yields a value
            bound = f"{first_col}[i]"
            bound_is_position = False
        for kind, col in chain_steps[1:]:
            if kind == "inverse":
                bound = f"_pos_{col}[{bound}]"
                bound_is_position = True
            else:
                # A position is used as-is; a value needs the 1->0 adjust
                adjust = "" if bound_is_position else value_adjust
                bound = f"{col}[{bound}{adjust}]"
                bound_is_position = False
        lines.append(f"    {result}.append({bound})")
        return lines

