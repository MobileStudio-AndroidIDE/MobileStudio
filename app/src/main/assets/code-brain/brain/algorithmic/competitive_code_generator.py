    def _t_palindrome_prefix(self, data: str, result: str) -> list[str]:
        """Shortest palindrome that has S as its prefix.

        The KMP failure function on (reverse(S) + '#' + S) finds the
        longest prefix of reverse(S) that is also a suffix of S — the
        longest palindromic suffix of S.  The answer appends the reverse
        of the remaining prefix — O(N), no quadratic palindrome check.
        """
        return [
            f"{data} = input().strip()",
            "t = " + data + "[::-1] + '#' + " + data,
            "fail = [0] * len(t)",
            "for i in range(1, len(t)):",
            "    k = fail[i - 1]",
            "    while k > 0 and t[i] != t[k]:",
            "        k = fail[k - 1]",
            "    if t[i] == t[k]:",
            "        k += 1",
            "    fail[i] = k",
            "L = fail[-1]",
            result + " = " + data + " + " + data +
            "[:len(" + data + ") - L][::-1]",
        ]

