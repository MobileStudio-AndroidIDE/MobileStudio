    def _t_stack_queries(self, result: str, details: dict) -> list[str]:
        """Generic query-driven stack simulation (body lines only).

        Q queries: "1 x" pushes x; "2" pops the top and outputs it.
        The initial stack state, when the problem declares one ("a
        stack of K items each labeled with the integer V"), starts as
        K copies of V; otherwise empty.  The empty-pop case outputs 0
        as a safe default (problems in this family usually guarantee a
        non-empty stack, making it moot).  The query count is already
        read by the plan's input-parsing step, so the queries are read
        from the remaining stdin tokens.
        """
        initial_count = int(details.get("initial_count", 0) or 0)
        initial_value = int(details.get("initial_value", 0) or 0)
        # the query count was read by the plan's input-parsing step
        # under the problem's declared variable name (e.g. "Q")
        q_var = details.get("count_var") or "q"
        init_lines = [f"stack = [{initial_value}] * {initial_count}"] \
            if initial_count > 0 else ["stack = []"]
        return [
            "import sys",
            "rest = sys.stdin.read().split()",
            "_idx = 0",
        ] + init_lines + [
            "out = []",
            f"for _ in range({q_var}):",
            "    c = rest[_idx]",
            "    _idx += 1",
            "    if c == '1':",
            "        x = int(rest[_idx])",
            "        _idx += 1",
            "        stack.append(x)",
            "    else:",
            "        if stack:",
            "            out.append(str(stack.pop()))",
            "        else:",
            "            out.append('0')",
            "print('\\n'.join(out))",
        ]

    def _t_query_simulation(self, ins: list, result: str, details: dict,
                            plan) -> list[str]:
        """Per-query monotone-increment simulation.

        N steps, each with a range condition [L_i, R_i] that increments
        the value by `increment`; Q queries each with an initial value.
        The trajectory is non-decreasing in the initial value, so the set
        of queries caught at each step is a contiguous interval — a sweep
        with a Fenwick tree over the value domain computes all answers in
        O((N + V) log V) without per-query simulation.
        """
        count_var = details.get("count_var", "q")
        lo_var = ins[0] if len(ins) > 0 else details.get("lo_var", "l")
        hi_var = ins[1] if len(ins) > 1 else details.get("hi_var", "r")
        increment = details.get("increment", 1)

        # Read the queries (the single query-var read step is consumed)
        return [
            f"queries = [int(input()) for _ in range({count_var})]",
            f"max_v = max(max({hi_var}), max(queries))",
            f"domain = max_v + len({lo_var}) * {increment} + 1",
            "tree = [0] * (domain + 2)",
            "",
            "def bit_add(i, delta):",
            "    while i <= domain:",
            "        tree[i] += delta",
            "        i += i & (-i)",
            "",
            "def bit_query(i):",
            "    s = 0",
            "    while i > 0:",
            "        s += tree[i]",
            "        i -= i & (-i)",
            "    return s",
            "",
            "def range_add(lo, hi, delta):",
            "    bit_add(lo, delta)",
            "    if hi + 1 <= domain:",
            "        bit_add(hi + 1, -delta)",
            "",
            f"for i in range(len({lo_var})):",
            f"    l_i = {lo_var}[i]",
            f"    r_i = {hi_var}[i]",
            "    lo, hi = 1, domain",
            "    while lo < hi:",
            "        mid = (lo + hi) // 2",
            f"        if mid + {increment} * bit_query(mid) >= l_i:",
            "            hi = mid",
            "        else:",
            "            lo = mid + 1",
            "    xlo = lo",
            "    lo, hi = xlo, domain",
            "    while lo < hi:",
            "        mid = (lo + hi + 1) // 2",
            f"        if mid + {increment} * bit_query(mid) <= r_i:",
            "            lo = mid",
            "        else:",
            "            hi = mid - 1",
            "    xhi = lo",
            f"    v = xlo + {increment} * bit_query(xlo)",
            "    if xlo <= xhi and l_i <= v <= r_i:",
            f"        range_add(xlo, xhi, {increment})",
            "",
            f"{result} = []",
            "for x in queries:",
            f"    {result}.append(x + {increment} * bit_query(x))",
        ]

    def _t_pair_count(self, data: str, result: str, details: dict) -> list[str]:
        """Count/max-match pairs satisfying a size relation."""
        rel = details.get("condition_kind", "at most half of")
        mode = details.get("mode", "count")

        if rel == "at most half of":
            cond = "a * 2 <= b"
        elif rel == "at least twice":
            cond = "a >= b * 2"
        elif rel == "at most":
            cond = "a <= b"
        elif rel == "at least":
            cond = "a >= b"
        elif rel in ("smaller than", "less than"):
            cond = "a < b"
        elif rel in ("greater than", "larger than"):
            cond = "a > b"
        else:
            raise ValueError(f"No condition template for relation '{rel}'")

        if mode == "max_matching":
            return [
                f"srt = sorted({data})",
                "count = 0",
                "i = 0",
                "j = len(srt) // 2",
                "while j < len(srt):",
                "    if i < len(srt) // 2 and srt[i] * 2 <= srt[j]:",
                "        count += 1",
                "        i += 1",
                "    j += 1",
                f"{result} = count",
            ]
        # Count mode: for a monotone size relation, sort and sweep a pointer
        # per large element (O(n log n)); self-pairs subtracted where the
        # relation permits equality.
        if rel == "at most half of":
            # self-pair impossible for positive values
            return [
                f"srt = sorted({data})",
                "count = 0",
                "i = 0",
                "for j in range(len(srt)):",
                "    while i < len(srt) and srt[i] * 2 <= srt[j]:",
                "        i += 1",
                "    count += i",
                f"{result} = count",
            ]
        if rel == "at least twice":
            return [
                f"srt = sorted({data})",
                "count = 0",
                "i = 0",
                "for j in range(len(srt)):",
                "    while i < len(srt) and srt[i] < srt[j] * 2:",
                "        i += 1",
                "    count += len(srt) - i",
                f"{result} = count",
            ]
        if rel == "at most":
            return [
                f"srt = sorted({data})",
                "count = 0",
                "i = 0",
                "for j in range(len(srt)):",
                "    while i < len(srt) and srt[i] <= srt[j]:",
                "        i += 1",
                "    count += i",
                "count -= len(srt)",
                f"{result} = count",
            ]
        if rel == "at least":
            return [
                f"srt = sorted({data})",
                "count = 0",
                "i = 0",
                "for j in range(len(srt)):",
                "    while i < len(srt) and srt[i] < srt[j]:",
                "        i += 1",
                "    count += len(srt) - i",
                "count -= len(srt)",
                f"{result} = count",
            ]
        if rel in ("smaller than", "less than"):
            return [
                f"srt = sorted({data})",
                "count = 0",
                "i = 0",
                "for j in range(len(srt)):",
                "    while i < len(srt) and srt[i] < srt[j]:",
                "        i += 1",
                "    count += i",
                f"{result} = count",
            ]
        # greater than / larger than
        return [
            f"srt = sorted({data})",
            "count = 0",
            "i = 0",
            "for j in range(len(srt)):",
            "    while i < len(srt) and srt[i] <= srt[j]:",
            "        i += 1",
            "    count += len(srt) - i",
            f"{result} = count",
        ]

