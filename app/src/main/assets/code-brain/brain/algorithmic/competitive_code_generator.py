    def _t_bfs(self, data: str, result: str, details: dict) -> list[str]:
        """General BFS over a graph (BODY LINES ONLY — the outer
        def solution() wraps them; the plan's input-parsing step already
        produced the graph variables).

        Objectives (derived from the problem's semantics, not
        per-problem): components / shortest / count / visit.
        Reuses the edge-list variables from the input parsing (u, v,
        N, M); falls back to reading stdin when the input parsing did
        not produce named collections.
        """
        n_var = details.get("n_var") or "n"
        m_var = details.get("m_var") or "m"
        u_var = details.get("u_var") or "u"
        v_var = details.get("v_var") or "v"
        directed = bool(details.get("directed"))
        objective = details.get("objective", "visit")
        # when the edge variables were NOT produced by the input
        # parsing (stdin-reading names), read the graph from stdin
        uses_stdin = u_var == "u" and v_var == "v" and \
            n_var == "n" and m_var == "m"
        lines = ["from collections import deque"]
        if uses_stdin:
            lines += [
                "data = list(map(int, sys.stdin.read().split()))",
                f"{n_var}, {m_var} = data[0], data[1]",
                f"{u_var} = data[2::2]",
                f"{v_var} = data[3::2]",
            ]
        lines += [
            # vertex ids are not always 1..N (0-based ids, or ids larger
            # than the edge count) — size the adjacency from the data
            f"V = max({n_var}, max({u_var}, default=0), "
            f"max({v_var}, default=0)) + 1",
            f"adj = [[] for _ in range(V)]",
            f"for i in range({m_var}):",
            f"    adj[{u_var}[i]].append({v_var}[i])",
        ]
        if not directed:
            lines += [f"    adj[{v_var}[i]].append({u_var}[i])"]
        if objective == "components":
            lines += [
                "visited = [False] * (len(adj))",
                "components = 0",
                "for s in range(1, len(adj)):",
                "    if visited[s]:",
                "        continue",
                "    components += 1",
                "    queue = deque([s])",
                "    visited[s] = True",
                "    while queue:",
                "        cur = queue.popleft()",
                "        for nxt in adj[cur]:",
                "            if not visited[nxt]:",
                "                visited[nxt] = True",
                "                queue.append(nxt)",
                f"{result} = components",
            ]
        elif objective == "shortest":
            lines += [
                "dist = [-1] * (len(adj))",
                "queue = deque([1])",
                "dist[1] = 0",
                "while queue:",
                "    cur = queue.popleft()",
                "    for nxt in adj[cur]:",
                "        if dist[nxt] == -1:",
                "            dist[nxt] = dist[cur] + 1",
                "            queue.append(nxt)",
                f"{result} = max(d for d in dist[1:] if d >= 0) if any(d >= 0 for d in dist[1:]) else -1",
            ]
        elif objective == "count":
            lines += [
                "visited = [False] * (len(adj))",
                "queue = deque([1])",
                "visited[1] = True",
                "count = 1",
                "while queue:",
                "    cur = queue.popleft()",
                "    for nxt in adj[cur]:",
                "        if not visited[nxt]:",
                "            visited[nxt] = True",
                "            count += 1",
                "            queue.append(nxt)",
                f"{result} = count",
            ]
        else:
            lines += [
                "visited = [False] * (len(adj))",
                "queue = deque([1])",
                "visited[1] = True",
                "while queue:",
                "    cur = queue.popleft()",
                "    for nxt in adj[cur]:",
                "        if not visited[nxt]:",
                "            visited[nxt] = True",
                "            queue.append(nxt)",
                f"{result} = sum(visited)",
            ]
        return lines

    def _t_dfs(self, data: str, result: str, details: dict) -> list[str]:
        """General DFS over a graph (body lines, iterative; same
        variable reuse as the BFS template)."""
        d = dict(details)
        d.setdefault("objective", "components")
        if d.get("objective") == "shortest":
            return self._t_bfs(data, result, d)
        n_var = d.get("n_var") or "n"
        m_var = d.get("m_var") or "m"
        u_var = d.get("u_var") or "u"
        v_var = d.get("v_var") or "v"
        directed = bool(d.get("directed"))
        objective = d["objective"]
        uses_stdin = u_var == "u" and v_var == "v" and \
            n_var == "n" and m_var == "m"
        lines = []
        if uses_stdin:
            lines += [
                "data = list(map(int, sys.stdin.read().split()))",
                f"{n_var}, {m_var} = data[0], data[1]",
                f"{u_var} = data[2::2]",
                f"{v_var} = data[3::2]",
            ]
        lines += [
            # vertex ids are not always 1..N (0-based ids, or ids larger
            # than the edge count) — size the adjacency from the data
            f"V = max({n_var}, max({u_var}, default=0), "
            f"max({v_var}, default=0)) + 1",
            f"adj = [[] for _ in range(V)]",
            f"for i in range({m_var}):",
            f"    adj[{u_var}[i]].append({v_var}[i])",
        ]
        if not directed:
            lines += [f"    adj[{v_var}[i]].append({u_var}[i])"]
        if objective == "components":
            lines += [
                "visited = [False] * (len(adj))",
                "components = 0",
                "for s in range(1, len(adj)):",
                "    if visited[s]:",
                "        continue",
                "    components += 1",
                "    stack = [s]",
                "    visited[s] = True",
                "    while stack:",
                "        cur = stack.pop()",
                "        for nxt in adj[cur]:",
                "            if not visited[nxt]:",
                "                visited[nxt] = True",
                "                stack.append(nxt)",
                f"{result} = components",
            ]
        else:
            lines += [
                "visited = [False] * (len(adj))",
                "stack = [1]",
                "visited[1] = True",
                "count = 1",
                "while stack:",
                "    cur = stack.pop()",
                "    for nxt in adj[cur]:",
                "        if not visited[nxt]:",
                "            visited[nxt] = True",
                "            count += 1",
                "            stack.append(nxt)",
                f"{result} = count",
            ]
        return lines

    def _t_sliding_window(self, data: str, result: str,
                          details: dict) -> list[str]:
        """General sliding-window scan (body lines).

        Window size k (from the constraints when declared, else every
        window); the aggregation comes from the output measure:
        max/min over windows, or count of windows satisfying the
        condition.  Reusable across problems — no per-problem logic.
        """
        k = details.get("window_k")
        direction = details.get("direction", "maximize")
        fn = "min" if direction == "minimize" else "max"
        lines = []
        if k:
            lines += [
                f"best = None",
                f"for i in range(len({data}) - {k} + 1):",
                f"    window = {data}[i:i + {k}]",
                f"    val = {fn}(window)",
                "    if best is None or val " + (">" if direction == "maximize" else "<") + " best:",
                "        best = val",
                f"{result} = best",
            ]
        else:
            # every window: count windows satisfying the condition.
            # No condition means the plan never stated WHAT to test —
            # rendering an always-true predicate would count every
            # window and silently mis-solve. Fail honestly: the
            # orchestrator tries the next hypothesis, or the standard
            # pipeline handles the request.
            cond = details.get("condition")
            if not cond:
                raise ValueError(
                    "sliding_window has neither window size nor condition: "
                    "the plan must state what each window is tested against")
            lines += [
                "count = 0",
                f"for i in range(len({data})):",
                f"    for j in range(i + 1, len({data}) + 1):",
                f"        window = {data}[i:j]",
                f"        if {cond}:",
                "            count += 1",
                f"{result} = count",
            ]
        return lines

    def _t_two_pointer(self, data: str, result: str,
                       details: dict) -> list[str]:
        """General two-pointer scan (body lines).

        Counts pairs (i < j) whose size relation holds after sorting,
        or finds the shortest/longest span satisfying a condition —
        derived from the plan's semantics.
        """
        rel = details.get("condition_kind", "")
        mode = details.get("mode", "count")
        if rel in ("at most half of", "at least twice", "at most",
                   "at least", "smaller than", "less than",
                   "greater than", "larger than"):
            # delegate to the pair-count pair relation (sorted scan)
            return self._t_pair_count(data, result, details)
        # generic pair scan with a condition from the plan
        cond = details.get("condition", "a < b")
        return [
            f"srt = sorted({data})",
            "count = 0",
            "i = 0",
            "j = len(srt) - 1",
            "while i < j:",
            f"    a, b = srt[i], srt[j]",
            f"    if {cond}:",
            "        count += len(srt) - j + 1 if j > i else 1",
            "        i += 1",
            "    else:",
            "        j -= 1",
            f"{result} = count",
        ]

    def _t_prefix_sum_exists(self, data: str, result: str,
                             details: dict) -> list[str]:
        """Does ANY contiguous range sum to zero? (boolean answer)

        A repeated prefix sum (or a prefix sum that returns to 0)
        marks a zero-sum range between the two occurrences — one pass,
        O(n) memory, and the result is a BOOL, never a count.
        """
        return [
            f"{result} = False",
            "seen = set()",
            "acc = 0",
            f"for x in {data}:",
            "    acc += x",
            "    if acc == 0 or acc in seen:",
            f"        {result} = True",
            "        break",
            "    seen.add(acc)",
        ]

    def _t_prefix_sum_zero(self, data: str, result: str, details: dict) -> list[str]:
        """Longest/shortest zero-sum contiguous range via prefix sums.

        maximize(length): track first occurrence of each prefix sum.
        minimize(length): track last occurrence of each prefix sum.
        """
        direction = details.get("direction", "maximize")
        if direction == "minimize":
            return [
                "last_seen = {0: -1}",
                "acc = 0",
                "best = -1",
                f"for i in range(len({data})):",
                f"    acc += {data}[i]",
                "    if acc in last_seen:",
                "        gap = i - last_seen[acc]",
                "        if best == -1 or gap < best:",
                "            best = gap",
                "    last_seen[acc] = i",
                f"{result} = best",
            ]
        return [
            "first_seen = {0: -1}",
            "acc = 0",
            "best = 0",
            f"for i in range(len({data})):",
            f"    acc += {data}[i]",
            "    if acc in first_seen:",
            "        gap = i - first_seen[acc]",
            "        if gap > best:",
            "            best = gap",
            "    else:",
            "        first_seen[acc] = i",
            f"{result} = best",
        ]

    def _t_kadane(self, data: str, result: str, details: dict) -> list[str]:
        """Maximum/minimum sum contiguous subarray (Kadane's algorithm)."""
        direction = details.get("direction", "maximize")
        fn = "min" if direction == "minimize" else "max"
        cmp = "<" if direction == "minimize" else ">"
        return [
            f"best = {data}[0]",
            f"cur = {data}[0]",
            f"for x in {data}[1:]:",
            f"    cur = {fn}(x, cur + x)",
            f"    if cur {cmp} best:",
            "        best = cur",
            f"{result} = best",
        ]

    def _t_iterate(self, data: str, result: str, details: dict) -> list[str]:
        """Iteration with optional nesting, filtering, and aggregation."""
        loop_var = details.get("loop_var", "i")
        loop_range = details.get("loop_range", data)
        nested = details.get("nested", False)
        nested_var = details.get("nested_var", "j")
        nested_range = details.get("nested_range")
        filter_condition = details.get("filter_condition")
        filter_source = details.get("filter_source")
        agg_type = details.get("agg_type", "count")

        if nested and nested_range:
            value_expr = filter_source if filter_source else f"{loop_var} * {nested_var}"
        else:
            value_expr = loop_var if filter_source in (None, "x") else filter_source

        lines = [f"{result} = 0", f"for {loop_var} in {loop_range}:"]
        prefix = "    "
        if nested and nested_range:
            lines.append(f"{prefix}for {nested_var} in {nested_range}:")
            prefix += "    "
        if filter_condition:
            lines.append(f"{prefix}if {filter_condition}:")
            prefix += "    "
        if agg_type == "sum":
            lines.append(f"{prefix}{result} += {value_expr}")
        else:
            lines.append(f"{prefix}{result} += 1")
        return lines

    def _t_check_property(self, data: str, result: str, details: dict) -> list[str]:
        """Property checks producing a boolean result."""
        check_type = (details.get("check_type") or "").lower()

        if check_type == "check_sorted":
            return [
                f"{result} = all({data}[i] <= {data}[i + 1] "
                f"for i in range(len({data}) - 1))"
            ]

        if check_type == "sorted_one_swap":
            exactly_one = bool(details.get("exactly_one"))
            adjacent_only = bool(details.get("adjacent_only"))
            lines = [
                f"_sorted_v = sorted({data})",
                f"_mism = [i for i in range(len({data})) if {data}[i] != _sorted_v[i]]",
            ]
            if exactly_one:
                lines.append("_ok = len(_mism) == 2")
            else:
                lines.append("_ok = len(_mism) == 0 or len(_mism) == 2")
            if adjacent_only:
                lines.append("if _ok and len(_mism) == 2:")
                lines.append("    _ok = _mism[1] - _mism[0] == 1")
            lines.append(f"{result} = _ok")
            return lines

        if check_type == "geometric_progression":
            return [
                f"if len({data}) < 2:",
                f"    {result} = True",
                f"elif {data}[0] == 0:",
                f"    {result} = all(x == 0 for x in {data})",
                "else:",
                f"    {result} = all({data}[i + 1] * {data}[0] == {data}[i] * {data}[1] "
                f"for i in range(len({data}) - 1))",
            ]

        if "increasing" in check_type or "decreasing" in check_type:
            strictly = "strictly" in check_type
            decreasing = "decreasing" in check_type
            if strictly:
                cmp = ">" if decreasing else "<"
            else:
                cmp = ">=" if decreasing else "<="
            return [
                f"{result} = all({data}[i] {cmp} {data}[i + 1] "
                f"for i in range(len({data}) - 1))"
            ]

        raise ValueError(f"No code template for property check '{check_type}'")

